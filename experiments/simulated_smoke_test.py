"""Smoke test: run the whole pipeline on SIMULATED inertial signal.

WHAT THIS IS: proof that windowing, feature extraction, the leave-one-driver-out
harness and the threshold baseline run end to end and produce metrics.

WHAT THIS IS NOT: evidence about driving behaviour. The signal here is generated by a
few lines of numpy, so the scores below say only that the code works and that the
evaluation is wired up correctly. They must not be read as classification results, and
they are replaced the moment a real recording is available.

Per-driver offsets are included deliberately so that leave-one-driver-out is actually
being asked to generalise across drivers rather than across copies of one driver.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.evaluate import compare_models, default_model, leave_one_group_out  # noqa: E402
from src.features import features_table  # noqa: E402
from src.windowing import WindowSpec, estimate_rate_hz, make_windows  # noqa: E402

RATE_HZ = 50.0
BEHAVIORS = {
    # label: (jerk scale, low-frequency drift amplitude)
    "normal": (0.6, 0.05),
    "aggressive": (1.9, 0.05),
    "drowsy": (0.5, 0.45),
}
SIGNALS = ["acc_x", "acc_y", "acc_z", "gyro_x", "gyro_y", "gyro_z"]


def simulate(n_drivers: int = 6, seconds_per_behavior: int = 240, seed: int = 0) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    frames = []
    for d in range(n_drivers):
        # Each driver has a persistent bias and gain: the thing LODO must survive.
        driver_bias = rng.normal(0, 0.15, size=len(SIGNALS))
        driver_gain = rng.normal(1.0, 0.12)
        t0 = 0.0
        for label, (jerk_scale, drift_amp) in BEHAVIORS.items():
            n = int(seconds_per_behavior * RATE_HZ)
            t = t0 + np.arange(n) / RATE_HZ
            cols = {}
            for j, name in enumerate(SIGNALS):
                noise = rng.normal(0, jerk_scale * driver_gain, size=n)
                # Drowsy driving: slow periodic drift with corrective inputs.
                drift = drift_amp * np.sin(2 * np.pi * 0.08 * t + rng.uniform(0, 6.28))
                cols[name] = noise * 0.25 + drift + driver_bias[j]
            frame = pd.DataFrame(cols)
            frame["t"] = t
            frame["label"] = label
            frame["driver"] = f"driver_{d:02d}"
            frames.append(frame)
            t0 = t[-1] + 1.0 / RATE_HZ
    return pd.concat(frames, ignore_index=True)


def main() -> None:
    out_dir = Path(__file__).resolve().parents[1] / "results"
    out_dir.mkdir(exist_ok=True)

    raw = simulate()
    print(f"Simulated samples: {len(raw):,} across {raw['driver'].nunique()} drivers")
    print(f"Estimated sampling rate: {estimate_rate_hz(raw['t']):.1f} Hz")

    for length_s in (2.0, 30.0):
        spec = WindowSpec(length_s=length_s, overlap=0.5)
        windows = make_windows(raw, SIGNALS, "t", "label", "driver", spec)
        table = features_table(windows, SIGNALS, RATE_HZ)
        print(f"\n=== {length_s:g} s windows: {len(table)} windows, "
              f"{len(table.columns) - 3} features ===")
        comparison = compare_models(table)
        print(comparison.round(3).to_string(index=False))
        comparison.to_csv(out_dir / f"smoke_comparison_{int(length_s)}s.csv", index=False)

        if length_s == 2.0:
            detail = leave_one_group_out(table, default_model())
            print("\nPer-driver folds (gradient-boosted trees):")
            print(detail["folds"].round(3).to_string(index=False))
            detail["folds"].to_csv(out_dir / "smoke_folds_2s.csv", index=False)
            print("\nPooled confusion matrix (rows = true):")
            print(detail["confusion"].to_string())
            detail["confusion"].to_csv(out_dir / "smoke_confusion_2s.csv")

    print("\nThese numbers measure the pipeline, not driving behaviour. "
          "The signal is generated.")


if __name__ == "__main__":
    main()
